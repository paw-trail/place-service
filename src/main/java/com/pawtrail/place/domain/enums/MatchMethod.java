package com.pawtrail.place.domain.enums;

/**
 * 이 소스가 어느 단계에서 장소에 붙었는지입니다.
 *
 * 이름 일치가 모든 단계의 전제입니다.
 * 주소가 같고 이름이 다른 쌍이 실측에 백여 건 있었습니다.
 * 북촌8경과 북촌문화센터, 스타필드코엑스몰과 다이소코엑스몰점 같은 것들입니다.
 *
 * 거짓 병합이 거짓 분리보다 훨씬 위험합니다.
 * 거짓 병합은 강남점 조건에 홍대점 원문을 붙이는 식으로 틀린 근거를 만드는데,
 * 근거 제시가 정체성인 서비스에 치명적입니다.
 * 그래서 애매하면 병합하지 않습니다.
 */
public enum MatchMethod {

    // 이 소스가 그 장소를 처음 만들었음
    PRIMARY,

    // 도로명 주소를 정규화한 값이 일치하고 이름도 일치함
    // 병합의 1순위 경로임
    ADDRESS,

    // 원본 좌표가 100m 안에 있고 이름도 일치함
    //
    // 50m 가 아니라 100m 인 이유는 소스마다 대표 좌표를 다르게 잡기 때문임
    // 건물 중심을 쓰는 곳과 입구를 쓰는 곳이 있어
    // 주소와 이름이 둘 다 같은데 좌표만 100m 넘게 떨어진 쌍이 실측에 있었음
    COORD_ORIGINAL,

    // 한쪽이 지오코딩 좌표이고 300m 안에 있으며 이름도 일치함
    // 둘 다 지오코딩이면 병합하지 않음
    COORD_GEOCODED
}
