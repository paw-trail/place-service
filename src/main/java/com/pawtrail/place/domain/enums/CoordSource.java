package com.pawtrail.place.domain.enums;

/**
 * 좌표가 어디서 왔는지입니다.
 *
 * 병합의 좌표 근접 판정에서 임계값이 값마다 다릅니다.
 * 지오코딩 좌표끼리는 병합하지 않습니다.
 * 오차가 겹치면 서로 다른 장소가 같은 좌표로 보이기 때문입니다.
 */
public enum CoordSource {

    // 소스가 준 측량 좌표 그대로
    // 이 값끼리는 100m 안에서 병합함
    ORIGINAL,

    // EPSG:5174 에서 4326 으로 변환한 것
    // 행정안전부 동물병원 CSV 가 여기 해당함
    //
    // 원본과 같은 100m 를 씀
    // 옮긴 5,258건 가운데 주소가 같은 기존 장소와 맞은 1,783쌍을 재었더니
    // 중앙값이 3m 이고 90분위가 20m 로 원본끼리도 나는 차이였음
    // 100m 를 넘긴 61건은 변환 오차가 아니라
    // 도로명주소 하나가 넓은 부지를 가리키는 곳이었음 (에버랜드 · 서울대 · 국립생태원)
    CONVERTED,

    // 주소를 카카오 API 로 좌표화한 것
    // 한쪽만 이 값일 때 300m 안에서 병합하고 둘 다면 병합하지 않음
    GEOCODED
}
