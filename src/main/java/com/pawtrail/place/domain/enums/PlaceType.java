package com.pawtrail.place.domain.enums;

/**
 * 서비스 카테고리입니다.
 *
 * 소스가 주는 원천 분류(lcls1~3)와 별개입니다.
 * 소스가 넷이라 분류 체계가 제각각이기 때문입니다.
 * 고캠핑에는 lclsSystm 이 없고 문화정보원은 자체 카테고리를 씁니다.
 *
 * 원천 분류를 place 에 함께 남겨 두므로
 * 여기로 옮기는 규칙을 나중에 바꿔도 다시 뽑을 수 있습니다.
 *
 * 컬럼에 CHECK 를 걸지 않았으므로 값이 늘어도 마이그레이션이 필요 없습니다.
 * 검증은 이 enum 이 합니다.
 */
public enum PlaceType {

    // 공원 · 하천 · 자연공원 · 산
    PARK,

    // 야영장 · 글램핑 · 카라반
    CAMPING,

    CAFE,

    // 펜션 · 호텔 · 모텔 · 호스텔
    STAY,

    // 박물관 · 미술관 · 문예회관
    CULTURE,

    // 체중 조건이 실제로 갈리는 카테고리라 ETC 에서 떼어 냈음
    // 야외 관광지는 대부분 전 견종이 통과하는데
    // 숙박과 레포츠에서 판정이 갈림
    LEISURE,

    RESTAURANT,

    // 위 어디에도 안 맞는 곳
    ETC,

    // 동물병원
    // 동반 조건이 없어 판정 대상이 아니며 판정 배지를 붙이지 않음
    VET
}
