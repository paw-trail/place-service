-- business_hours 와 closed_days 의 폭을 넓힙니다.
--
-- 공사가 주는 값이 "시간" 이 아니라 안내문입니다.
-- 가장 긴 usetime 이 553 자였습니다.
--   [1월]- 첫출발 10:30- 정상출발 (평일) 18:30 / (금요일~일요일) 20:00[2월]- ...
-- 월별로 운항 시각이 다른 유람선이나 계절별로 나뉘는 시설이 이런 형태로 옵니다.
--
-- 잘라 담지 않는 이유는 잘린 안내문이 더 나쁘기 때문입니다.
-- 200 자에서 자르면 2 월 이후가 사라진 채로 사용자에게 보입니다.
-- 전화번호에서 "잘린 번호는 담지 않는다" 로 정했던 것과 같은 기준인데,
-- 여기는 아예 안 담는 선택지가 없습니다. 영업시간이 비면 화면이 허전해집니다.
--
-- 종전 폭에 근거가 없기도 했습니다.
-- 명세가 varchar(200) 과 varchar(100) 을 왜 그렇게 두었는지 적어 두지 않았고,
-- 실제 데이터를 보기 전에 정한 값입니다.
--
-- 600 인 이유는 실측 최장 553 에 여유를 둔 것입니다.
-- lcls1 을 79 자 실측에 100 으로 잡은 것과 같은 방식입니다.

ALTER TABLE place ALTER COLUMN business_hours TYPE varchar(600);

-- 휴무일도 함께 넓힙니다.
--
-- restdate 자체는 최장 96 자로 종전 폭 안에 들어갑니다.
-- 그런데 분류마다 필드 이름이 갈려 restdateculture 나 restdatefood 가 오는 행이 있고
-- 그쪽이 더 긴 경우가 있어 실제 적재에서 넘쳤습니다.
--
-- 200 인 이유는 영업시간과 같은 성격이되 관측된 최장이 그 절반 아래이기 때문입니다.
ALTER TABLE place ALTER COLUMN closed_days TYPE varchar(200);
