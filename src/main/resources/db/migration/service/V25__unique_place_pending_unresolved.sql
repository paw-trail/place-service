-- 처리하지 않은 대기 값이 중복으로 쌓이지 않게 막습니다.
--
-- 같은 값이면 대기 행을 만들지 않기로 했습니다.
-- 소스가 값을 고치지 않는 한 같은 차이가 수집마다 발견되는데,
-- 그때마다 행을 만들면 목록에 같은 값이 여러 줄 뜨고
-- 반려한 것도 다시 올라와 관리자가 같은 판단을 되풀이하게 됩니다.
--
-- 그 규칙을 애플리케이션에서만 지키면 뚫립니다.
-- 있는지 보고 없으면 넣는 사이에 다른 트랜잭션이 끼어들면 둘 다 통과합니다.
-- 수집을 동시에 두 번 돌리면 실제로 일어납니다.
--
-- 같은 문제를 place_source_link 의 uq_place_source 가 제약으로 풀었습니다.
-- 재수집이 멱등이 되는 근거가 그 제약이며, 여기도 같은 자리입니다.
--
-- 승인된 것은 제외합니다.
-- 승인되면 place 의 값이 새 값이 되어 수집이 달라졌다고 보지 않으므로
-- 같은 값으로 다시 들어올 일이 없습니다.
-- 오히려 넣어 두면 승인한 뒤 소스가 값을 되돌렸다가 다시 바꾼 경우를 막게 됩니다.
--
-- new_value 가 NULL 인 행은 이 인덱스에 걸리지 않습니다.
-- 수집은 새 값이 비면 달라진 것으로 보지 않아 그런 행을 만들지 않습니다.
--
-- 목록 조회용 인덱스는 여전히 두지 않습니다.
-- 이 표는 관리자가 손댄 장소에서만 행이 생겨 지금 한 건도 없습니다.

CREATE UNIQUE INDEX uq_place_pending_unresolved
    ON place_pending_update (place_id, field_name, new_value)
    WHERE status IN ('PENDING', 'REJECTED');
